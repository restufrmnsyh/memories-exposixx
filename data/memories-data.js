// Helper Functions
const getMemoriesByYear = (year) => {
  return memoriesData.filter(memory => memory.year === year);
};

const getMemoriesByCategory = (category) => {
  return memoriesData.filter(memory => memory.category === category);
};

const getAllYears = () => {
  return [...new Set(memoriesData.map(memory => memory.year))];
};

const getAllCategories = () => {
  return [...new Set(memoriesData.map(memory => memory.category))];
};

// Sort memories by date (chronological order)
const sortedMemories = memoriesData.sort((a, b) => new Date(a.date) - new Date(b.date));

// Export for use in other files
if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    memoriesData,
    getMemoriesByYear,
    getMemoriesByCategory,
    getAllYears,
    getAllCategories,
    sortedMemories
  };
}
